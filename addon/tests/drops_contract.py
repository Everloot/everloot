"""Run with: uv run --with lupa python addon/tests/drops_contract.py

Drop sources in item tooltips (modules/drops.lua): the Desktop App writes the public drop rates into the
EverlootPrices slot addon beside the prices (addon/tests/fixtures/EverlootPrices.lua, regenerated by
companion/scripts/write-prices-fixture.ts). A price is labelled a price, a drop names its denominator (loot
windows), its installs and its date, a missing value says so, and nothing is written to SavedVariables.
"""
import re
from pathlib import Path
from lupa.lua51 import LuaRuntime

root = Path(__file__).parents[1]
fixture = (Path(__file__).parent / "fixtures" / "EverlootPrices.lua").read_text(encoding="utf-8")

# The slot file's shape, as the addon reads it: one checksummed string beside the realms, rows grouped by item
# and best rate first, every row from three installs or more, and a data date.
block = re.search(r'\["drops"\] = \{ \["data"\] = "([^"]*)", \["sum"\] = (\d+), \["dataAsOf"\] = "([^"]*)", \["fetchedAt"\] = "([^"]*)" \}', fixture)
assert block, "the drops block is in the slot file, data first"
data, dates = block.group(1), (block.group(3), block.group(4))
rows = [r.split(",") for r in data.split(";")]
assert all(re.fullmatch(r"\d+,[no],\d+,\d+,\d+,\d+", ",".join(r)) for r in rows), rows
assert all(int(r[5]) >= 3 and 0 < int(r[4]) and int(r[3]) <= int(r[4]) for r in rows), "public rates only"
items = [int(r[0]) for r in rows]
assert items == sorted(items), "rows are grouped by item"
linen = [int(r[3]) / int(r[4]) for r in rows if r[0] == "2589"]
assert linen == sorted(linen, reverse=True) and len(linen) == 4, "an item's sources come best rate first"
assert all(re.fullmatch(r"\d{4}-\d\d-\d\dT[\d:.]+Z", d) for d in dates), dates

toc = (root / "Everloot.toc").read_text(encoding="utf-8")
assert "modules\\drops.lua" in toc and "EverlootPrices" in toc, "drops module in the TOC, the slot addon an optional dependency"
source = (root / "modules" / "drops.lua").read_text(encoding="utf-8")
code = "\n".join(line.split("--")[0] for line in source.splitlines())
# The module reads the slot file only: not the player's SavedVariables, not the network, not another addon.
assert "EverlootDB" not in code and "SendAddonMessage" not in code and "C_ChatInfo" not in code, "drops.lua reads only EverlootPricesDB"

lua = LuaRuntime()
lua.execute("""
now = 1000000
time = function() return now end
date = function() return '2026-10-21T10:00:00Z' end
printed = {}
print = function(msg) printed[#printed + 1] = tostring(msg) end
function said(pattern) for _, p in ipairs(printed) do if string.find(p, pattern) then return true end end return false end
SlashCmdList = {}
CreateFrame = function()
  return { RegisterEvent = function() end, SetScript = function(self, s, f) if s == 'OnEvent' then self.onEvent = f end end,
    HookScript = function() end, SetSize = function() end, SetPoint = function() end, SetText = function() end }
end
timers = {}
C_Timer = { After = function(seconds, f) table.insert(timers, { seconds = seconds, f = f }) end }
function drain() while #timers > 0 do table.remove(timers, 1).f() end end
GetRealmName = function() return 'Forever' end
tooltipCalls = {}
Enum = { TooltipDataType = { Item = 0 } }
TooltipDataProcessor = { AddTooltipPostCall = function(kind, f) table.insert(tooltipCalls, { kind = kind, f = f }) end }
function tooltipFor(itemId)
  local tip = { lines = {} }
  tip.AddLine = function(self, text) table.insert(self.lines, text) end
  for _, c in ipairs(tooltipCalls) do c.f(tip, { id = itemId }) end
  return table.concat(tip.lines, '\\n'), #tip.lines
end

-- SavedVariables as the client writes them: every key and value, sorted, so two states compare byte for byte.
function serialize(v)
  if type(v) ~= 'table' then return type(v) == 'string' and string.format('%q', v) or tostring(v) end
  local keys = {}
  for k in pairs(v) do keys[#keys + 1] = k end
  table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
  local out = {}
  for _, k in ipairs(keys) do out[#out + 1] = '[' .. serialize(k) .. ']=' .. serialize(v[k]) end
  return '{' .. table.concat(out, ',') .. '}'
end
""")
for file in ["core.lua", "modules/auctions.lua", "modules/prices.lua", "modules/drops.lua"]:
    lua.execute((root / file).read_text(encoding="utf-8"))

# Without the Desktop App's file a tooltip carries no Everloot line: nothing to show, and nothing to nag about.
# The first item tooltip says once per install, in chat, where community prices come from.
lua.execute("""
Everloot.frame.onEvent(nil, 'ADDON_LOADED', 'Everloot')
Everloot:InitModules()
assert(#tooltipCalls == 1, 'one tooltip hook for prices and drops')
printed = {}
assert(tooltipFor(2589) == '', 'no file, no line')
assert(#printed == 1 and string.find(printed[1], 'Everloot Desktop App (everloot.app/addon)', 1, true), 'the first tooltip points to the app once: ' .. table.concat(printed, ' | '))
assert(tooltipFor(765) == '' and #printed == 1, 'the second tooltip says nothing more')
Everloot.frame.onEvent(nil, 'ADDON_LOADED', 'Everloot')
printed = {}
assert(tooltipFor(2589) == '' and #printed == 0, 'nor after a reload: once per install')
svBefore = serialize(EverlootDB)
""")

lua.execute(fixture)
lua.execute("""
Everloot:ResetPrices()

-- A price and a drop source: the price is labelled market, each rate has its loot windows, installs and date.
local linen = tooltipFor(2589)
assert(linen:find('Everloot market 2s 5c'), 'the price is labelled a market price: ' .. linen)
assert(linen:find('Everloot drop: NPC 116 · 12%.4%% %(42 of 340 loot windows%) · 5 installs'), linen)
assert(linen:find('NPC 94 · 6%.0%% %(12 of 200 loot windows%) · 3 installs'), linen)
assert(linen:find('NPC 474 · 4%.2%%'), 'three sources shown, best rate first: ' .. linen)
assert(not linen:find('NPC 6 '), 'the fourth source is counted, not listed: ' .. linen)
assert(linen:find('drop rates from uploads as of 2026%-10%-20 · 1 more source'), linen)
assert(not linen:find('no price') and not linen:find('no drop'), 'nothing is missing: ' .. linen)
local a, b = linen:find('Everloot market'), linen:find('Everloot drop')
assert(a < b, 'prices first, then drops')

-- A price, no drop source: the missing drop says so.
local herb = tooltipFor(765)
assert(herb:find('Everloot market unrecorded') and herb:find('Everloot: no drop source reported by 3 installs'), herb)
assert(not herb:find('Everloot drop:'), herb)

-- A drop source, no price: the missing price says so, and the object kind is named.
local drop = tooltipFor(12345)
assert(drop:find('Everloot drop: NPC 61 · 1%.2%% %(1 of 80 loot windows%) · 3 installs'), drop)
assert(drop:find('Everloot: no price on Forever yet') and not drop:find('Everloot market'), drop)
assert(tooltipFor(2770):find('Everloot drop: object 1731 · 96%.8%% %(300 of 310 loot windows%) · 6 installs'))

-- Neither: one grey line under the header names both gaps; no number is shown that the file does not hold.
local none, lines = tooltipFor(424242)
assert(none:match('|t Everloot\\nEverloot: no price on Forever yet · no drop source reported by 3 installs$') and lines == 2, none)
assert(not tooltipFor(258):find('Everloot drop'), '258 does not match 2589: rows are matched whole')
""")

# A drop row under three installs is never shown, whatever the file says; a bad checksum hides drops only.
lua.execute("""
local data = '2589,n,116,42,340,5;2589,n,7,40,41,2;31337,n,9,1,2,1'
EverlootPricesDB.drops = { data = data, sum = Everloot.Adler32(data), dataAsOf = '' }
Everloot:ResetPrices()
local linen = tooltipFor(2589)
assert(linen:find('NPC 116') and not linen:find('NPC 7 '), 'two installs is not three: ' .. linen)
assert(linen:find('drop rates: upload date unknown'), 'a missing date says so: ' .. linen)
assert(tooltipFor(31337):find('no drop source reported by 3 installs'))

EverlootPricesDB.drops.sum = 5
Everloot:ResetPrices()
printed = {}
local tampered = tooltipFor(2589)
assert(said('drop sources failed their checksum'), 'a bad checksum is reported')
assert(tampered:find('Everloot market 2s 5c') and not tampered:find('Everloot drop:') and tampered:find('Everloot: drop sources failed their checksum'), tampered)

-- A file from an app that does not write drops yet: prices show, and the drop gap is named as the file's.
EverlootPricesDB.drops = nil
Everloot:ResetPrices()
local old = tooltipFor(2589)
assert(old:find('Everloot market') and old:find('Everloot: drop sources not in the price file yet'), old)
""")

# A large drops block is checked a slice per frame; until it passes, no drop line and no "missing" line.
lua.execute("""
local big = {}
for id = 1, 5000 do big[#big + 1] = string.format('%d,n,%d,%d,%d,%d', id, 100000 + id, 3, 300, 4) end
local data = table.concat(big, ';')
collectgarbage('collect')
local before = collectgarbage('count')
EverlootPricesDB.drops = { data = data, sum = Everloot.Adler32(data), dataAsOf = '2026-10-20T06:00:00.000Z' }
Everloot:ResetPrices()
timers = {}
assert(not tooltipFor(42):find('Everloot drop'), 'nothing before the checksum has passed')
drain()
assert(tooltipFor(42):find('Everloot drop: NPC 100042 · 1%.0%% %(3 of 300 loot windows%) · 4 installs'))
collectgarbage('collect')
dropBytes = #data
dropKb = collectgarbage('count') - before
""")
drop_bytes, drop_kb = lua.eval("dropBytes"), lua.eval("dropKb")
# The Desktop App caps the file at 5,000 rows (desktop/src/main/market.ts MAX_DROP_ROWS). Loading the file holds the
# string once; the addon's ;-delimited copy, measured here, holds it a second time: well under half a megabyte.
assert drop_bytes < 160_000 and drop_kb < 400, (drop_bytes, drop_kb)

# /everloot price shows the same drop lines in chat.
lua.execute("""
EverlootPricesDB = nil
""")
lua.execute(fixture)
lua.execute("""
Everloot:ResetPrices()
GetItemInfo = function() return nil end
printed = {}
SlashCmdList.EVERLOOT('price 2589'); drain()
assert(said('Everloot market 2s 5c') and said('Everloot drop: NPC 116'), table.concat(printed, '\\n'))
printed = {}
SlashCmdList.EVERLOOT('price 424242'); drain()
assert(said('No price for this item on this realm yet') and said('No drop source reported by 3 installs'), table.concat(printed, '\\n'))

-- The SavedVariables cost of all of the above: none. Tooltips and the command read the slot file and write nothing.
svAfter = serialize(EverlootDB)
""")
sv_before, sv_after = lua.eval("svBefore"), lua.eval("svAfter")
assert sv_before == sv_after, "showing prices and drops writes nothing to SavedVariables"
# With the file in the game, an install that has not had the pointer never gets it: there is nothing to explain.
lua.execute("""
EverlootDB.priceFileHint = nil
printed = {}
tooltipFor(2589)
assert(#printed == 0 and EverlootDB.priceFileHint == nil, table.concat(printed, ' | '))
""")
print(f"drops_contract: ok (SavedVariables +0 bytes; 5,000-row drops block {drop_bytes:,} bytes, ~{drop_kb:.0f} KB Lua memory)")
