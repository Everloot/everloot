// Collection's game-file names and encounters, gated by the public 3-install agreement snapshot.
// From web/: npx tsx scripts/build-instance-data.ts [--snapshot <complete public corpus JSON>]
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { confirmedEntrances, instanceBosses, instanceFactsFromRecords } from "../../kb/src/instances";

const root = fileURLToPath(new URL("../../", import.meta.url));
const snapshotPath = resolve(root, "addon/data/agreed-instances.json");
if (process.argv[2] === "--snapshot") {
  const corpus = JSON.parse(readFileSync(resolve(process.argv[3]), "utf8"));
  if (!corpus.ok || corpus.next !== null || corpus.records.length !== corpus.total || !corpus.dataAsOf) {
    throw new Error("A complete, dated public corpus response is required; combine pages before snapshotting");
  }
  const facts = instanceFactsFromRecords(corpus.records);
  const asOf = new Date(corpus.dataAsOf);
  const snapshot = {
    source: "https://everloot.app/api/corpus/public?kinds=instance_entrance,encounter",
    asOf: corpus.dataAsOf,
    label: "Agreed by players, 3 installs; Data from Everloot (https://everloot.app), CC BY-SA 4.0",
    entrances: confirmedEntrances(facts.entrances, asOf).map(({ instanceMapId, instanceType }) => ({ instanceMapId, instanceType })),
    bosses: [...instanceBosses(facts.encounters, asOf)].flatMap(([instanceMapId, bosses]) =>
      bosses.map(({ encounterId }) => ({ instanceMapId, encounterId }))),
  };
  writeFileSync(snapshotPath, JSON.stringify(snapshot, null, 2) + "\n");
}

export function renderInstanceData(): string {
  const snapshot = JSON.parse(readFileSync(snapshotPath, "utf8"));
  const client = JSON.parse(readFileSync(resolve(root, "web/src/data/game-data/client-encounters.json"), "utf8"));
  const map = JSON.parse(readFileSync(resolve(root, "web/src/data/game-data/map.json"), "utf8"));
  const names = JSON.parse(readFileSync(resolve(root, "addon/data/instance-map-names.json"), "utf8"));
  const world: Record<number, string> = { 2789: "Lord Kazzak", 2791: "Azuregos", 2804: "Prince Thunderaan", 2832: "Emerald dragons" };
  const lines = [
    "-- Collection instance table, generated by web/scripts/build-instance-data.ts from",
    "-- client-encounters.json, map.json, addon/data/instance-map-names.json and addon/data/agreed-instances.json.",
    "-- instance-data.test.ts checks parity. Each source build and the agreement date are recorded below.",
    "-- Found in game files / agreed by players. World bosses are found in game files, unconfirmed.",
    "", "Everloot = Everloot or {}", "Everloot.InstanceData = {",
    `  build = ${JSON.stringify(client.build.version)},`, `  mapNamesBuild = ${JSON.stringify(names.build)},`, `  asOf = ${JSON.stringify(snapshot.asOf)},`, "  instances = {",
  ];
  for (const [key, encounters] of Object.entries(client.instances ?? client.encounters)) {
    const id = Number(key);
    const entrance = snapshot.entrances.find((e: { instanceMapId: number; instanceType: string }) => e.instanceMapId === id && ["party", "raid"].includes(e.instanceType));
    const bosses = (encounters as { id: number; name: string }[]).filter((b) => world[id] || snapshot.bosses.some((s: { instanceMapId: number; encounterId: number }) => s.instanceMapId === id && s.encounterId === b.id));
    if (id === 2720 || !bosses.length) continue;
    const place = map.entrances.find((e: { mapId: number }) => e.mapId === id)
      ?? names.instances.find((e: { id: number }) => e.id === id);
    const name = world[id] ?? place?.name;
    if (!name) throw new Error(`No game-file instance name for ${id}`);
    // Boss agreement can precede entrance agreement. Game-file type fills that gap, never inventing reports.
    const raid = entrance ? entrance.instanceType === "raid" : place?.raid;
    const group = world[id] ? "World bosses" : raid ? "Raids" : "Dungeons";
    lines.push(`    { id = ${id}, name = ${JSON.stringify(name)}, group = ${JSON.stringify(group)}, unconfirmed = ${Boolean(world[id])}, bosses = {`);
    for (const b of bosses) lines.push(`      { id = ${b.id}, name = ${JSON.stringify(b.name)} },`);
    lines.push("    } },");
  }
  return [...lines, "  },", "}", ""].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(root, "addon/modules/instance_data.lua"), renderInstanceData());
}
